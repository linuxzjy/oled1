const uint8_t *font5x7_glyph(char c)
{
    uint32_t i;

    for (i = 0u; i < (sizeof(g_font) / sizeof(g_font[0])); i++) {
        if (g_font[i].ch == c) {
            return g_font[i].rows;
        }
    }
    return g_font[0].rows;   /* 空格 */
}
